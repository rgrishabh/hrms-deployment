#!/usr/bin/env bash
# Makes a client's overlay from Terraform outputs, for the client's PRIVATE repository. Base and
# components stay here, referenced at a fixed tag; only values live with the client.
#   scripts/new-client-overlay.sh <terraform-env-dir|outputs.json> <target-dir> <deployment-ref>
# Then fill in <target-dir>/brand.env and app.env. Needs terraform (unless given JSON) and jq.
set -euo pipefail
SOURCE=${1:?usage: new-client-overlay.sh <terraform-env-dir|outputs.json> <target-dir> <deployment-ref>}
TARGET=${2:?target dir required}; REF=${3:?deployment ref, for example v2.0.0}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
[ ! -e "$TARGET" ] || { echo "error: $TARGET exists" >&2; exit 1; }
if [ -d "$SOURCE" ]; then JSON=$(terraform -chdir="$SOURCE" output -json overlay_values); else JSON=$(cat "$SOURCE"); fi
v() { jq -er ".$1" <<<"$JSON"; }
TIER=$(v tier); RDS=$(v rds_master_secret_name); CERT=$(v certificate_arn); LOGS=$(v alb_logs_bucket); REGION=$(v region)

cp -R "$ROOT/k8s/overlays/prod" "$TARGET"
REMOTE="https://github.com/rgrishabh/hrms-deployment//k8s"
sed -i.bak -E \
  -e "s#\.\./\.\./base#$REMOTE/base?ref=$REF#" \
  -e "s#\.\./\.\./components/tier-[a-z]+#$REMOTE/components/tier-$TIER?ref=$REF#" \
  -e "s#rds!db-00000000-0000-0000-0000-000000000000#$RDS#g" \
  -e '/^# Template for one client/,/^# folder, with its values/d' \
  "$TARGET/kustomization.yaml"

cat > "$TARGET/infra-patch.yaml" <<PATCH
# Generated by scripts/new-client-overlay.sh from terraform output overlay_values.
PATCH
if [ "$TIER" != low ]; then
  cat >> "$TARGET/infra-patch.yaml" <<PATCH
apiVersion: v1
kind: ServiceAccount
metadata:
  name: hrms-backend
  annotations:
    eks.amazonaws.com/role-arn: $(v backend_role_arn)
---
apiVersion: v1
kind: ServiceAccount
metadata:
  name: hrms-worker
  annotations:
    eks.amazonaws.com/role-arn: $(v worker_role_arn)
---
apiVersion: v1
kind: ServiceAccount
metadata:
  name: hrms-secrets
  annotations:
    eks.amazonaws.com/role-arn: $(v secrets_role_arn)
---
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: hrms
  annotations:
    alb.ingress.kubernetes.io/certificate-arn: $CERT
    alb.ingress.kubernetes.io/security-groups: $(v alb_security_group_id)
    alb.ingress.kubernetes.io/manage-backend-security-group-rules: "true"
    alb.ingress.kubernetes.io/load-balancer-attributes: routing.http.drop_invalid_header_fields.enabled=true,deletion_protection.enabled=true,idle_timeout.timeout_seconds=60,access_logs.s3.enabled=true,access_logs.s3.bucket=$LOGS,access_logs.s3.prefix=alb
---
PATCH
fi
cat >> "$TARGET/infra-patch.yaml" <<PATCH
apiVersion: external-secrets.io/v1
kind: SecretStore
metadata:
  name: aws
spec:
  provider:
    aws:
      region: $REGION
PATCH
rm -f "$TARGET/kustomization.yaml.bak"
echo "overlay written to $TARGET (tier-$TIER). Now edit brand.env, app.env and brand/. Keep it private."
